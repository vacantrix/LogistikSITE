/**
 * Флаги автопроверки документов (движок src/lib/verify.ts) — не все являются
 * предупреждениями. Когда уверенность распознавания ниже автопорога, но поле
 * принято по подтверждениям (строгий формат, совпадение с заявкой), строка
 * флага — положительный итог, и показывать её жёлтым треугольником нельзя.
 */
export function isPositiveIssue(issue: string): boolean {
  return issue.includes('принято по подтверждениям')
}
