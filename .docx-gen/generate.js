// ── Компоненты ───────────────────────────────────────────────────
function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    keepNext: true,
    spacing: { before: 360, after: 160, line: 312 },
    children: [new TextRun({ text, bold: true, color: NAVY, size: 32, font: A })],
  });
}

function p(text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { firstLine: 709 },
    spacing: { after: 80, line: 312 },
    children: [new TextRun({ text, color: BLACK, size: 24, font: T })],
  });
}

function bullet(lead, rest) {
  return new Paragraph({
    style: "ListParagraph",
    numbering: { reference: "bullets", level: 0 },
    spacing: { after: 60, line: 312 },
    alignment: AlignmentType.LEFT,
    children: [
      new TextRun({ text: lead, bold: true, color: BODY, size: 24, font: T }),
      new TextRun({ text: rest, color: BODY, size: 24, font: T }),
    ],
  });
}

function step(text) {
  return new Paragraph({
    style: "ListParagraph",
    numbering: { reference: "steps", level: 0 },
    spacing: { after: 60, line: 312 },
    alignment: AlignmentType.LEFT,
    children: [new TextRun({ text, color: BODY, size: 24, font: T })],
  });
}

function tableTitle(text) {
  return new Paragraph({
    keepNext: true,
    spacing: { before: 200, after: 80, line: 312 },
    children: [new TextRun({ text, bold: true, color: NAVY, size: 21, font: T })],
  });
}

function figCaption(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { after: 160, line: 312 },
    children: [new TextRun({ text, color: CAPT, size: 21, font: T })],
  });
}

// Таблица: шапка бирюзовая, строки с чередованием, ячейки с отступами
function mkTable(widths, header, rows) {
  const headerRow = new TableRow({
    tableHeader: true,
    cantSplit: true,
    children: header.map((text, i) => new TableCell({
      width: { size: widths[i], type: WidthType.PERCENTAGE },
      shading: { type: ShadingType.CLEAR, fill: TEAL },
      margins: { top: 80, bottom: 80, left: 120, right: 120 },
      children: [new Paragraph({
        spacing: { line: 312 },
        alignment: AlignmentType.LEFT,
        children: [new TextRun({ text, bold: true, color: "FFFFFF", size: 21, font: A })],
      })],
    })),
  });
  const dataRows = rows.map((cells, r) => new TableRow({
    cantSplit: true,
    children: cells.map((text, i) => new TableCell({
      width: { size: widths[i], type: WidthType.PERCENTAGE },
      shading: r % 2 === 1 ? { type: ShadingType.CLEAR, fill: ZEBRA } : undefined,
      margins: { top: 70, bottom: 70, left: 120, right: 120 },
      children: [new Paragraph({
        spacing: { line: 312 },
        alignment: AlignmentType.LEFT,
        children: [new TextRun({ text, color: BODY, size: 21, font: T })],
      })],
    })),
  }));
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 6, color: TEAL },
      bottom: { style: BorderStyle.SINGLE, size: 6, color: TEAL },
      left: noBorder, right: noBorder,
      insideHorizontal: { style: BorderStyle.SINGLE, size: 2, color: GRAYLN },
      insideVertical: noBorder,
    },
    margins: { top: 70, bottom: 70, left: 120, right: 120 },
    rows: [headerRow, ...dataRows],
  });
}

