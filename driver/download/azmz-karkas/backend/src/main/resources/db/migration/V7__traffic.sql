-- ============================================================================
-- V7. Пробки (канал 3): агрегат скоростей по сегментам дорог.
--
-- Решение сессии «Онлайн-карты и пробки»:
--  * источник №1 — собственная телеметрия: position_ping (V6) матчится на
--    сегменты дорожного графа (OSRM /products или своя сетка по way_id OSM),
--    скорости агрегируются джобой раз в минуту (медиана по окну 15 мин,
--    минимум 3 разных ТС на сегмент — анти-выброс и анти-дебанонимизация);
--  * источник №2 (опция, этап MVP+) — обмен с другими перевозчиками
--    (консорциум/партнёры) тем же контрактом traffic_segment;
--  * источник №3 (опция) — коммерческий провайдер трафика с допустимой для
--    РФ моделью лицензирования. Yandex Traffic API запрещён лицензией на
--    закрытый код — как и тайлы, см. раздел 7 README;
--  * раздача — как пометки (канал 2): снимком по bbox, НЕ в личный журнал:
--    GET /api/driver/v1/traffic?minLat&minLon&maxLat&maxLon&since;
--  * офлайн — клиент держит последний снимок; слой «водители для водителей»
--    (road_mark) дополняет картину без сети.
--
-- 152-ФЗ: сегмент НЕ содержит ПДн — это агрегат по ≥3 машинам без
-- идентификаторов; персональные треки остаются в position_ping с retention.
-- ============================================================================

CREATE TABLE traffic_segment (
    id             text PRIMARY KEY,            -- стабильный id сегмента графа (напр. "osm:way:12345:0")
    title          text,                        -- человекочитаемо: «А-146 · Верхнебаканский»
    geom           geography (LineString, 4326) NOT NULL,
    level          smallint NOT NULL
                   CHECK (level BETWEEN 0 AND 3),   -- 0 свободно | 1 замедление | 2 пробка | 3 затор
    speed_kmh      integer NOT NULL,            -- текущая агрегированная скорость
    free_flow_kmh  integer NOT NULL,            -- свободная скорость сегмента (профиль OSRM)
    sample_count   integer NOT NULL,            -- сколько ТС в агрегате (для отладки, ≥3)
    on_route       boolean NOT NULL DEFAULT false, -- сегмент входит в активные коридоры рейсов
    updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_traffic_segment_geom    ON traffic_segment USING GIST (geom);
CREATE INDEX idx_traffic_segment_updated ON traffic_segment (updated_at);

COMMENT ON TABLE traffic_segment IS
    'Агрегат скоростей по сегментам дорог из телеметрии парка. retention 2 ч (чистка джобой): старый трафик не показываем.';

